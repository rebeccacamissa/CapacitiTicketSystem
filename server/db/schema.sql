-- =====================================================================
-- CAPACITI Candidate Support & Service Request System: PostgreSQL schema
-- Owner: Member C (State Machine Core & Audit Log)
--
-- Business rules are enforced HERE, at the database level:
--   * status_transitions + trg_requests_status_guard: the ticket state machine
--     (illegal jumps, missing assignee/resolution, or a move with no audit row
--     raise an exception)
--   * transition_overrides: one-shot, admin-only override tokens
--   * stage decision triggers: official programme stages move one step at a time,
--     backward moves are admin-only, and every change needs an audited decision
--   * audit_log and stage_decisions are append-only
-- The API validates first for friendly errors, but even a raw SQL UPDATE cannot
-- bypass these rules. Every statement is idempotent (safe to run on each start).
--
-- Timestamps are stored as ISO-8601 UTC text (e.g. 2026-11-10T08:00:00.000Z).
-- =====================================================================

CREATE OR REPLACE FUNCTION now_iso() RETURNS text LANGUAGE sql VOLATILE AS $$
  SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

-- now_iso() shifted by an interval, e.g. iso_shift('-7 days').
CREATE OR REPLACE FUNCTION iso_shift(shift text) RETURNS text LANGUAGE sql VOLATILE AS $$
  SELECT to_char((clock_timestamp() AT TIME ZONE 'UTC') + shift::interval, 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

-- An ISO timestamp shifted by an interval.
CREATE OR REPLACE FUNCTION iso_add(ts text, shift text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT to_char((ts::timestamptz AT TIME ZONE 'UTC') + shift::interval, 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

-- Hours between two ISO timestamps (b - a).
CREATE OR REPLACE FUNCTION iso_hours(a text, b text) RETURNS double precision LANGUAGE sql IMMUTABLE AS $$
  SELECT EXTRACT(EPOCH FROM (b::timestamptz - a::timestamptz)) / 3600.0
$$;

