-- =====================================================================
-- TRIGGERS: ticket state machine
-- =====================================================================
CREATE OR REPLACE FUNCTION fn_requests_insert_open() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status <> 'Open' THEN
    RAISE EXCEPTION 'ILLEGAL_TRANSITION: new requests must start in Open';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_requests_insert_open BEFORE INSERT ON requests
  FOR EACH ROW EXECUTE FUNCTION fn_requests_insert_open();

CREATE OR REPLACE FUNCTION fn_requests_status_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status IS NOT DISTINCT FROM NEW.status THEN RETURN NEW; END IF;

  IF NOT EXISTS (SELECT 1 FROM status_transitions WHERE from_status = OLD.status AND to_status = NEW.status)
     AND NOT EXISTS (
       SELECT 1 FROM transition_overrides o JOIN users u ON u.id = o.authorized_by
       WHERE o.request_id = NEW.id AND o.to_status = NEW.status AND u.role = 'admin' AND u.is_active = 1) THEN
    RAISE EXCEPTION 'ILLEGAL_TRANSITION: transition not permitted by workflow';
  END IF;

  IF NEW.status IN ('Assigned', 'In Progress', 'Waiting for Candidate') AND NEW.assigned_to IS NULL THEN
    RAISE EXCEPTION 'ASSIGNEE_REQUIRED: request must be assigned to a staff member';
  END IF;

  IF NEW.status = 'Resolved' AND (NEW.resolution IS NULL OR length(trim(NEW.resolution)) = 0) THEN
    RAISE EXCEPTION 'RESOLUTION_REQUIRED: a resolution must be recorded';
  END IF;

  -- The most recent audit row for this request must describe exactly this move.
  IF NOT EXISTS (
       SELECT 1 FROM audit_log a
       WHERE a.id = (SELECT MAX(id) FROM audit_log WHERE request_id = NEW.id)
         AND a.action = 'STATUS_CHANGE' AND a.old_status = OLD.status AND a.new_status = NEW.status) THEN
    RAISE EXCEPTION 'AUDIT_REQUIRED: status change has no matching audit_log entry';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_requests_status_guard BEFORE UPDATE OF status ON requests
  FOR EACH ROW EXECUTE FUNCTION fn_requests_status_guard();

CREATE OR REPLACE FUNCTION fn_requests_assignee_staff() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.assigned_to IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM users WHERE id = NEW.assigned_to AND role IN ('support', 'admin') AND is_active = 1) THEN
    RAISE EXCEPTION 'INVALID_ASSIGNEE: assignee must be active support or admin staff';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_requests_assignee_staff BEFORE UPDATE OF assigned_to ON requests
  FOR EACH ROW EXECUTE FUNCTION fn_requests_assignee_staff();

CREATE OR REPLACE FUNCTION fn_requests_consume_override() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM transition_overrides WHERE request_id = NEW.id;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_requests_consume_override AFTER UPDATE OF status ON requests
  FOR EACH ROW EXECUTE FUNCTION fn_requests_consume_override();

CREATE OR REPLACE FUNCTION fn_audit_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'AUDIT_LOG_IMMUTABLE: % entries cannot be modified or deleted', TG_TABLE_NAME;
END $$;
CREATE OR REPLACE TRIGGER trg_audit_no_update BEFORE UPDATE ON audit_log FOR EACH ROW EXECUTE FUNCTION fn_audit_immutable();
CREATE OR REPLACE TRIGGER trg_audit_no_delete BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION fn_audit_immutable();

-- =====================================================================
-- TRIGGERS: official stage decisions
-- =====================================================================
CREATE OR REPLACE FUNCTION fn_stage_decision_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  cur  text := COALESCE((SELECT stage FROM candidate_stages WHERE candidate_id = NEW.candidate_id), 'enrolled');
  f    int  := (SELECT sort_order FROM programme_stages WHERE key = NEW.from_stage);
  t    int  := (SELECT sort_order FROM programme_stages WHERE key = NEW.to_stage);
BEGIN
  IF NEW.direction = 'initial' THEN
    IF EXISTS (SELECT 1 FROM candidate_stages WHERE candidate_id = NEW.candidate_id) THEN
      RAISE EXCEPTION 'STAGE_ALREADY_SET: candidate already has an official stage';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.to_stage = cur THEN
    RAISE EXCEPTION 'STAGE_UNCHANGED: candidate is already at this stage';
  END IF;
  IF NEW.from_stage IS DISTINCT FROM cur THEN
    RAISE EXCEPTION 'STAGE_STALE: the decision does not start from the current stage';
  END IF;
  IF NEW.direction = 'forward' AND t <> f + 1 THEN
    RAISE EXCEPTION 'STAGE_SKIP: stages move forward one step at a time';
  END IF;
  IF NEW.direction = 'backward' AND t >= f THEN
    RAISE EXCEPTION 'STAGE_DIRECTION: a backward decision must move to an earlier stage';
  END IF;
  IF NEW.direction = 'backward' AND NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.decided_by AND role = 'admin' AND is_active = 1) THEN
    RAISE EXCEPTION 'STAGE_BACKWARD_ADMIN_ONLY: only an administrator can move a candidate back a stage';
  END IF;
  IF NEW.direction = 'forward'
     AND NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.decided_by AND role = 'admin' AND is_active = 1)
     AND NOT EXISTS (
       SELECT 1 FROM users u
       JOIN facilitator_streams fs ON fs.user_id = u.id
       JOIN candidate_profiles cp ON cp.user_id = NEW.candidate_id AND cp.stream = fs.stream
       WHERE u.id = NEW.decided_by AND u.role = 'facilitator' AND u.is_active = 1) THEN
    RAISE EXCEPTION 'STAGE_NOT_AUTHORISED: only an admin or the stream facilitator can approve this stage';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_stage_decision_guard BEFORE INSERT ON stage_decisions
  FOR EACH ROW EXECUTE FUNCTION fn_stage_decision_guard();

CREATE OR REPLACE FUNCTION fn_candidate_stage_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.stage = NEW.stage THEN
    RAISE EXCEPTION 'STAGE_UNCHANGED: candidate is already at this stage';
  END IF;
  IF (TG_OP = 'INSERT' AND NEW.stage <> 'enrolled' OR TG_OP = 'UPDATE') AND NOT EXISTS (
       SELECT 1 FROM stage_decisions d
       WHERE d.id = (SELECT MAX(id) FROM stage_decisions WHERE candidate_id = NEW.candidate_id)
         AND d.to_stage = NEW.stage
         AND (TG_OP = 'INSERT' OR d.from_stage = OLD.stage)) THEN
    RAISE EXCEPTION 'STAGE_AUDIT_REQUIRED: stage change has no matching stage decision';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_candidate_stage_guard BEFORE INSERT OR UPDATE OF stage ON candidate_stages
  FOR EACH ROW EXECUTE FUNCTION fn_candidate_stage_guard();

CREATE OR REPLACE TRIGGER trg_stage_decisions_no_update BEFORE UPDATE ON stage_decisions FOR EACH ROW EXECUTE FUNCTION fn_audit_immutable();
