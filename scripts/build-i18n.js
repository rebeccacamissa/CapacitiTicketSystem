'use strict';
/**
 * Builds translation dictionaries from i18n-source/*.js
 *   → public/js/i18n/{zu,xh,af,nso}.js   (browser, ES modules)
 *   → server/i18n/{zu,xh,af,nso}.js      (Cammy replies, CommonJS)
 * and reports any Cammy template that has no translation yet.
 *   npm run i18n
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const LANGS = ['zu', 'xh', 'af', 'nso'];
const sources = ['ui', 'pages', 'cammy'].map((n) => require(path.join(ROOT, 'i18n-source', `${n}.js`)));
const merged = Object.assign({}, ...sources);

const header = (lang) => `// GENERATED by scripts/build-i18n.js from i18n-source/*.js — do not edit by hand.\n// Language: ${lang}. Drafted for CAPACITI; native-speaker review pending.\n`;
let problems = 0;
for (const [i, lang] of LANGS.entries()) {
  const dict = {};
  for (const [en, tr] of Object.entries(merged)) {
    if (!Array.isArray(tr) || tr.length !== LANGS.length) { console.warn(`Malformed entry: ${en}`); problems += 1; continue; }
    // variables must survive translation
    const vars = (en.match(/\{\w+\}/g) || []).sort().join();
    if ((tr[i].match(/\{\w+\}/g) || []).sort().join() !== vars) { console.warn(`[${lang}] variable mismatch: ${en}`); problems += 1; }
    dict[en] = tr[i];
  }
  const body = JSON.stringify(dict, null, 1);
  fs.mkdirSync(path.join(ROOT, 'public/js/i18n'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, `public/js/i18n/${lang}.js`), `${header(lang)}export default ${body};\n`);
  fs.writeFileSync(path.join(ROOT, `server/i18n/${lang}.js`), `${header(lang)}module.exports = ${body};\n`);
}

// Coverage check for Cammy: every T('...') / act('...') template should be translated.
const svc = fs.readFileSync(path.join(ROOT, 'server/modules/cammy/cammy.service.js'), 'utf8');
const used = new Set();
for (const m of svc.matchAll(/\b(?:T|act)\(\s*(['"`])((?:(?!\1)[^\\]|\\.)+)\1/g)) used.add(m[2].replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/\\"/g, '"'));
for (const m of svc.matchAll(/SUGGEST = \{([\s\S]*?)\};/g)) for (const q of m[1].matchAll(/'([^']+)'/g)) used.add(q[1]);
const missing = [...used].filter((k) => !merged[k] && !/^\w+$/.test(k));
if (missing.length) { console.warn('Cammy strings without translations:'); missing.forEach((k) => console.warn(`  - ${k.slice(0, 90)}`)); }
console.log(`Built ${LANGS.length} languages × ${Object.keys(merged).length} strings. ${problems} problem(s), ${missing.length} untranslated Cammy string(s).`);
